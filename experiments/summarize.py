"""Collect results/*.json into results/SUMMARY.md (the only source of numbers quoted in the README)."""

import json

from _common import RES


def load(name):
    return json.loads((RES / f"{name}.json").read_text())


def sci(x):
    return f"{x:.2e}"


rows = []
d = load("exp01_curvature_invariants")
rows.append(("01", "Schwarzschild K(r) log-log slope", f"{d['schwarzschild_loglog_slope']:.6f}", "-6 (K = 48 M^2/r^6)"))
rows.append(("01", "Kerr K: engine vs closed form, max rel. err.", sci(d["kerr_max_relative_error"]), "round-off"))
d = load("exp02_effective_potential_orbits")
rows.append(
    ("02", "ISCO / photon sphere (symbolic)", f"{d['isco_symbolic']} / {d['photon_sphere_symbolic']}", "6M / 3M")
)
d = load("exp03_orbit_precession")
rows.append(
    (
        "03",
        "Periapsis advance: geodesic vs quadrature, max rel. diff.",
        sci(d["max_geodesic_vs_quad_rel"]),
        "rtol 1e-12",
    )
)
rows.append(
    ("03", "Slope of abs(exact/(6 pi M/p) - 1) vs p", f"{d['slope_of_deviation_from_leading']:.2f}", "-1 (O(M/p))")
)
d = load("exp04_light_deflection")
rows.append(
    ("04", "Deflection: geodesic vs quadrature, max rel. diff.", sci(d["max_geodesic_vs_exact_rel"]), "finite r0")
)
rows.append(
    (
        "04",
        "Slopes of residual after 1st / 2nd order",
        f"{d['slope_err_first_order']:.2f} / {d['slope_err_second_order']:.2f}",
        "-2 / -3",
    )
)
d = load("exp05_integrator_convergence")
rows.append(("05", "RK4 observed order", f"{d['rk4_observed_order']:.2f}", "4"))
d = load("exp06_newtonian_limit")
rows.append(
    (
        "06",
        "Circular-orbit proper period: numeric vs exact, max abs. diff.",
        sci(d["max_abs_numeric_minus_exact"]),
        "rtol 1e-12",
    )
)
rows.append(("06", "Slope of period correction vs r", f"{d['loglog_slope']:.2f}", "-1"))
d = load("exp07_gravitational_waves")
rows.append(("07", "Linear deviation vs exact separation: slope in amplitude", f"{d['loglog_slope']:.2f}", "2"))
d = load("exp08_cosmology")
for k, v in d.items():
    rows.append(
        (
            "08",
            f"{k}: max rel. error / constraint",
            f"{sci(v['max_rel_error'])} / {sci(v['max_constraint'])}",
            "rtol 1e-11",
        )
    )
d = load("exp09_kerr")
rows.append(("09", "Kerr ISCO: literature vs W''=0, max discrepancy", sci(d["max_isco_discrepancy"]), "root-finder"))
rows.append(
    (
        "09",
        "Circular-orbit radial acceleration (engine Christoffels)",
        sci(d["circular_geodesic_radial_acceleration"]),
        "round-off",
    )
)
d = load("exp10_scalar_scattering")
rows.append(("10", "Max abs(1 - T - R) over grid (l<=3)", sci(d["max_flux_residual"]), "rtol 1e-10"))
rows.append(
    (
        "10",
        "T0/(16 w^2) at w=0.005, 0.01, 0.02, 0.05",
        ", ".join(f"{x:.4f}" for x in d["T0_over_16w2"]),
        "-> 1 as w -> 0",
    )
)
rows.append(("10", "Sensitivity to r*_max (l=2, w=0.3)", sci(d["rstar_max_sensitivity_l2_w0.3"]), ""))
d = load("exp11_second_order_perturbation")
rows.append(("11", "G^(1) vanishes; G^(2)_tt", f"{d['G1_is_zero']}; {d['G2_tt']}", ""))
rows.append(("11", "Truncation-error slope in eps", f"{d['truncation_error_slope']:.2f}", "4 (G_tt even in eps)"))
d = load("exp12_tidal_tensor")
rows.append(("12", "Tidal tensor E_ij (Cartan frame)", d["E_ij"], "diag(-2M, M, M)/r^3"))

lines = [
    "# Results summary",
    "",
    "Generated by `experiments/summarize.py` from `results/*.json`. Do not edit by hand.",
    "",
    "| Exp. | Quantity | Measured | Reference / expectation |",
    "|---|---|---|---|",
]
lines += [f"| {a} | {b} | {c} | {e} |" for a, b, c, e in rows]
(RES / "SUMMARY.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
